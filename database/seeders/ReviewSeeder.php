<?php

namespace Database\Seeders;

use App\Models\Product;
use App\Models\Review;
use Illuminate\Database\Seeder;

/**
 * Тестовые отзывы на товары: 2–4 отзыва на каждый товар
 * с разными оценками и датами за последние ~60 дней.
 */
class ReviewSeeder extends Seeder
{
    private const AUTHORS = [
        'Алексей', 'Мария', 'Дмитрий', 'Екатерина', 'Иван',
        'Ольга', 'Сергей', 'Анна', 'Павел', 'Наталья',
        'Максим', 'Юлия',
    ];

    private const COMMENTS_BY_RATING = [
        5 => [
            'Отличный товар, полностью доволен покупкой! Рекомендую.',
            'Работает идеально, лучше и не ожидал. Пять звёзд!',
            'Лучшее соотношение цены и качества на рынке.',
            'Пользуюсь уже месяц — никаких нареканий. Брал бы снова.',
            'Заказывал второй раз, качество стабильно отличное.',
        ],
        4 => [
            'Хороший товар, но есть мелкие недочёты. В целом доволен.',
            'За свои деньги отличный вариант, небольшие придирки есть.',
            'Достойное качество, доставка быстрая. Минус звезда за комплектацию.',
            'Впечатления положительные, хотя кое-что можно было бы сделать лучше.',
        ],
        3 => [
            'Нормально за свои деньги, но ожидал большего.',
            'Не плохой, но и не идеальный. Есть о чём подумать перед покупкой.',
            'Средне: часть функций работает хорошо, часть — нет.',
            'После недели использования появились небольшие претензии.',
        ],
        2 => [
            'Разочарован покупкой, ожидал другого качества.',
            'Частые сбои в работе, пришлось обращаться в поддержку.',
            'Не рекомендую: за эти деньги есть варианты лучше.',
        ],
        1 => [
            'Полностью разочарован, товар оказался бракованным.',
            'Не советую никому, вернуть бы деньги.',
        ],
    ];

    public function run(): void
    {
        Product::query()->each(function (Product $product): void {
            $seed = crc32($product->name);

            $count = $seed % 3 + 2; // 2–4 отзыва на товар

            for ($i = 0; $i < $count; $i++) {
                $rating = $this->pickRating($seed, $i);
                $comments = self::COMMENTS_BY_RATING[$rating];

                Review::create([
                    'product_id' => $product->id,
                    'author_name' => self::AUTHORS[($seed + $i * 7) % count(self::AUTHORS)],
                    'rating' => $rating,
                    'comment' => $comments[($seed + $i * 3) % count($comments)],
                    'created_at' => now()->subDays(($seed + $i * 13) % 60)->subHours(($seed + $i) % 24),
                    'updated_at' => now(),
                ]);
            }
        });
    }

    /**
     * Детерминированная оценка: в основном 4–5, реже 3 и ниже.
     */
    private function pickRating(int $seed, int $index): int
    {
        return match (($seed >> $index) % 10) {
            0, 1, 2, 3 => 5,
            4, 5, 6 => 4,
            7, 8 => 3,
            9 => ($seed >> $index) % 2 === 0 ? 2 : 1,
        };
    }
}
